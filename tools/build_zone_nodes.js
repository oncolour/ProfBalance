// Aggregates GatherMate2's Forever node data (Wowhead export) into per-zone node counts.
// Usage: node tools/build_zone_nodes.js > ProfBalance/ZoneNodes.lua
const fs = require("fs");
const base = "C:/Program Files (x86)/World of Warcraft/_forever_/Interface/AddOns/GatherMate2_Data/Forever/";
function parse(file) {
  const txt = fs.readFileSync(base + file, "utf8");
  const zones = {};
  let cur = null;
  for (const line of txt.split(/\r?\n/)) {
    const z = line.match(/^\t\[(\d+)\] = \{/);
    if (z) { cur = z[1]; zones[cur] = zones[cur] || {}; continue; }
    const n = line.match(/^\t\t\[\d+\] = (\d+),/);
    if (n && cur) zones[cur][n[1]] = (zones[cur][n[1]] || 0) + 1;
  }
  return zones;
}
const mines = parse("MiningData.lua");
const herbs = parse("HerbalismData.lua");
const ids = [...new Set([...Object.keys(mines), ...Object.keys(herbs)])].map(Number).sort((a, b) => a - b);
const out = [];
out.push("-- Generated by tools/build_zone_nodes.js from GatherMate2_Data (Forever, Wowhead export v2026-10-17).");
out.push("-- [uiMapID] = { mining = { [nodeID] = spawnCount }, herbs = { [nodeID] = spawnCount } }");
out.push("local _, ns = ...");
out.push("ns.ZoneNodes = {");
for (const id of ids) {
  const fmt = (t) => Object.entries(t || {}).sort((a, b) => b[1] - a[1]).map(([k, v]) => `[${k}]=${v}`).join(", ");
  out.push(`\t[${id}] = { mining = { ${fmt(mines[id])} }, herbs = { ${fmt(herbs[id])} } },`);
}
out.push("}");
process.stdout.write(out.join("\n") + "\n");
